// Поверхность: вступительное окно (#onboardingModal).
// Ни от одной другой поверхности не зависит — самый чистый лист графа.
//
// ОКНО НЕ ПРИХОДИТ САМО (UIP-P3, решение владельца 2026-08-25). Ни на первом
// запуске, ни в каком другом состоянии. До того пакета оно открывалось на первом
// запуске и закрывалось навсегда первым же закрытием; теперь автопоказа нет
// вообще, и вместе с ним ушёл вопрос «показывать ли».
//
// ВХОД РОВНО ОДИН НА КАНАЛ, И С NAV-P1 ОНИ РАЗНЫЕ. На вебе это кнопка #aboutBtn
// в шапке; в приложении — строка #menuAboutBtn в меню шапки, под тем же именем
// «О приложении», слово в слово. Обе зовут openOnboardingModal() ниже, и
// одновременно видимой бывает ровно одна из них: раскрывает их
// surfaces/channel.js, как и всё остальное, что зависит от канала.
//
// ЧТО УШЛО ВМЕСТЕ С НИМ, И ПОЧЕМУ ЦЕЛИКОМ. checkAndShowOnboarding() читала
// onboarding_dismissed, closeOnboardingModal() его писала. Читателя не стало —
// значит, писать его означало бы класть в браузер родителя значение, которое
// никто никогда не прочитает. Ключ и обе его функции убраны из core/storage.js;
// значения, уже лежащие в браузерах, оставлены нетронутыми, по прецеденту
// UIP-DL-001: чистка — это тоже запись, и повода для неё нет.
//
// ЗАКРЫТИЕ ТЕПЕРЬ ЗНАЧИТ ТОЛЬКО «ЗАКРЫТЬ». Выходов по-прежнему три — ✕,
// «Закрыть», клик по фону, — и они наконец равнозначны буквально, а не по
// договорённости: ни один из них ничего не запоминает, потому что помнить
// нечего. История, чтобы её не восстанавливали по диффам: L3-P3 сняла отсюда
// галочку «Больше не показывать» (FIU-DL-001 долг 14), сделав «прочитал» из
// любого из трёх закрытий, — до неё запоминалось ровно одно из трёх, и родитель,
// закрывший окно крестиком, встречал его снова на каждом холодном старте.
//
// И ПОЭТОМУ КНОПКА В ШАПКЕ ВАЖНЕЕ, ЧЕМ БЫЛА. Внутри этого окна лежат ДВА
// предмета, достижимых только через него: ссылка на политику конфиденциальности
// (PDR-035, аннотация 2026-08-21 — у ссылки ровно два носителя, это окно и эта
// кнопка) и строка о том, что у браузерной копии нет резервной. Раз окно само не
// приходит, кнопка обязана быть видимой в любом состоянии, включая первый
// запуск. Это утверждение исполняется, а не декларируется:
// app/tests/behavior.spec.js, UIP-P3-INV-001.
//
// Контрол в шапке, а обработчик здесь — по тому же разделению, что у архива и
// дневника: surfaces/channel.js решает, ПРЕДЛАГАЕТСЯ ли действие на этом
// канале, а поверхность решает, ЧТО оно делает. По тому же разделению строку
// меню вешает на этот же openOnboardingModal() surfaces/menu.js: у окна один
// обработчик, сколько бы входов в него ни было.

// Вступительное окно
export function openOnboardingModal() {
    document.getElementById('onboardingModal').classList.add('show');
}

function closeOnboardingModal() {
    document.getElementById('onboardingModal').classList.remove('show');
}

export function wireOnboarding() {
    // Обработчики вступительного окна
    document.getElementById('onboardingCloseBtn').addEventListener('click', closeOnboardingModal);
    document.getElementById('onboardingModalClose').addEventListener('click', closeOnboardingModal);
    document.getElementById('onboardingModal').addEventListener('click', (e) => {
        if (e.target.id === 'onboardingModal') {
            closeOnboardingModal();
        }
    });

    // Вход веб-канала: открыть окно, сколько угодно раз. Вход нативного канала
    // вешает surfaces/menu.js на тот же openOnboardingModal().
    document.getElementById('aboutBtn').addEventListener('click', openOnboardingModal);
}
